create table if not exists public.names (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 100),
  created_at timestamptz not null default now()
);

alter table public.names enable row level security;

grant usage on schema public to anon;
grant select, insert on table public.names to anon;
grant usage, select on sequence public.names_id_seq to anon;

create policy "Allow public demo reads"
  on public.names for select
  to anon
  using (true);

create policy "Allow public demo inserts"
  on public.names for insert
  to anon
  with check (char_length(trim(name)) between 1 and 100);
